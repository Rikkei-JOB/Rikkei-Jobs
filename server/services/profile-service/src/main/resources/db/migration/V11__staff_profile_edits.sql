CREATE TABLE profile_edits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES candidate_profiles(user_id),
    staff_id UUID NOT NULL,
    field VARCHAR(32) NOT NULL CHECK (field IN ('headline', 'summary', 'selfSkills')),
    old_value TEXT NOT NULL,
    new_value TEXT NOT NULL,
    reason TEXT NOT NULL CHECK (LENGTH(TRIM(reason)) > 0),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_candidate_profiles_visibility_updated_at ON candidate_profiles(visibility, updated_at);
