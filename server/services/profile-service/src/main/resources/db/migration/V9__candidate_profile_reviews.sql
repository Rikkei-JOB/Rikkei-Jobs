ALTER TABLE candidate_profiles DROP CONSTRAINT ck_candidate_visibility;
ALTER TABLE candidate_profiles ADD CONSTRAINT ck_candidate_visibility
    CHECK (visibility IN ('PRIVATE', 'PENDING', 'PUBLIC', 'REJECTED'));
ALTER TABLE candidate_profiles ADD COLUMN consent_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE candidate_profiles ADD COLUMN consent_withdrawn_at TIMESTAMP(6) WITH TIME ZONE;

CREATE TABLE profile_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES candidate_profiles(user_id),
    action VARCHAR(10) NOT NULL CHECK (action IN ('SUBMIT', 'APPROVE', 'REJECT', 'WITHDRAW')),
    reason TEXT,
    actor_id UUID NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CHECK (action <> 'REJECT' OR (reason IS NOT NULL AND LENGTH(TRIM(reason)) > 0))
);
CREATE INDEX ix_profile_reviews_user_id_id ON profile_reviews(user_id, id);
